//! Joins the firmware to the circuit simulation.
//!
//! The SPICE deck `sim/decks/liveness_firmware_trace.cir` drives the simulated
//! charge pump, Q3 and K1 coil with the RELAY_PULSE waveform the real
//! `PulseBudget` emits, not with an ideal square wave. This test produces that
//! waveform and fails if the committed copy is stale, so the simulation can
//! never be run against pulse logic the firmware no longer has.
//!
//! Regenerate with `UPDATE_LIVENESS_TRACE=1 cargo test --test liveness_trace`.
//!
//! What this does NOT cover: the timing of the real esp_timer task. Tick
//! times here are chosen by the scenario, not measured on a chip.

use safety_core::liveness::{PulseBudget, MAX_TICK_GAP_US, PERMIT_US, PRECHARGE_EDGES, PULSE_HALF_PERIOD_US};
use std::fmt::Write as _;
use std::path::PathBuf;

const END_US: u32 = 800_000;
const LOOP_PERIOD_US: u32 = 5_000;
/// The loop pass lands just after a tick, so no two events share a timestamp.
const LOOP_PHASE_US: u32 = 100;
const ENTRY_US: u32 = 10_000;
const STOP_US: u32 = 300_000;
const FLASH_START_US: u32 = 150_000;
const HIGH_V: &str = "3.3";

/// What the safety loop does on one pass.
#[derive(Clone, Copy, PartialEq)]
enum Pass {
    Renew,
    Cancel,
    /// The loop is hung: it does not run at all.
    Hung,
}

struct Trace {
    /// (time, level after the change) for every change on the pin.
    pin: Vec<(u32, bool)>,
    /// First loop pass at which the firmware considers the gate precharged,
    /// i.e. when it would let the relay be commanded.
    precharged_at: Option<u32>,
    /// Passes after `precharged_at` on which precharge was lost again.
    precharge_losses: u32,
}

fn simulate(tick_times: &[u32], end_us: u32, pass_at: impl Fn(u32) -> Pass) -> Trace {
    let budget = PulseBudget::new();
    let mut trace = Trace { pin: Vec::new(), precharged_at: None, precharge_losses: 0 };
    let mut level = false;
    let mut ticks = tick_times.iter().copied().peekable();
    let mut pass_time = LOOP_PHASE_US;
    while pass_time < end_us || ticks.peek().is_some() {
        let next_tick = ticks.peek().copied().unwrap_or(u32::MAX);
        if next_tick <= pass_time {
            ticks.next();
            let new_level = budget.tick(next_tick);
            if new_level != level {
                level = new_level;
                trace.pin.push((next_tick, level));
            }
        } else {
            match pass_at(pass_time) {
                Pass::Renew => {
                    budget.renew(pass_time);
                    if budget.precharged(pass_time) {
                        trace.precharged_at.get_or_insert(pass_time);
                    } else if trace.precharged_at.is_some() {
                        trace.precharge_losses += 1;
                    }
                }
                Pass::Cancel => budget.cancel(),
                Pass::Hung => {}
            }
            pass_time += LOOP_PERIOD_US;
        }
    }
    trace
}

fn steady_ticks() -> Vec<u32> {
    (0..END_US / PULSE_HALF_PERIOD_US).map(|i| i * PULSE_HALF_PERIOD_US).collect()
}

fn seconds(us: u32) -> String {
    format!("{}.{:06}", us / 1_000_000, us % 1_000_000)
}

/// A SPICE piecewise-linear source with 1 us edges.
fn pwl(out: &mut String, name: &str, node: &str, changes: &[(u32, bool)]) {
    writeln!(out, "V{name} {node} 0 PWL(0 0").unwrap();
    for &(time, level) in changes {
        let (before, after) = if level { ("0", HIGH_V) } else { (HIGH_V, "0") };
        writeln!(out, "+ {} {before} {} {after}", seconds(time), seconds(time + 1)).unwrap();
    }
    writeln!(out, "+ )").unwrap();
}

fn last_change(trace: &Trace) -> u32 {
    trace.pin.last().expect("the pin toggled").0
}

fn generate() -> String {
    let mut out = String::new();
    out.push_str(
        "* GENERATED by firmware/esp32_rs/safety_core/tests/liveness_trace.rs from the\n\
         * real PulseBudget. Do not edit: that test fails if this file is stale.\n",
    );
    let entry_then = |after_stop: Pass| {
        move |now: u32| {
            if now < ENTRY_US {
                Pass::Cancel
            } else if now < STOP_US {
                Pass::Renew
            } else {
                after_stop
            }
        }
    };

    // HANG: a normal entry, then the safety loop stops running at 300 ms while
    // the timer keeps going. The relay is commanded when the firmware says
    // the gate is precharged.
    let hang = simulate(&steady_ticks(), END_US, entry_then(Pass::Hung));
    let commanded = hang.precharged_at.expect("the entry precharges");
    assert_eq!(hang.precharge_losses, 0);
    assert!(commanded - ENTRY_US >= PRECHARGE_EDGES * PULSE_HALF_PERIOD_US);
    // Last renewal was one loop period before the hang; pulses must be gone a
    // permit later, and the pin must be left low.
    let last_renewal = STOP_US - LOOP_PERIOD_US + LOOP_PHASE_US;
    assert!(last_change(&hang) <= last_renewal + PERMIT_US, "{}", last_change(&hang));
    assert!(!hang.pin.last().unwrap().1, "the pin must rest low");
    pwl(&mut out, "PIN_HANG", "pin_hang", &hang.pin);
    pwl(&mut out, "MARK_ENTRY", "mark_entry", &[(ENTRY_US, true)]);
    pwl(&mut out, "CMD", "cmd", &[(commanded, true)]);
    pwl(&mut out, "MARK_STOP", "mark_stop", &[(last_renewal, true)]);

    // CANCEL: the same entry, but at 300 ms another task forces Proxy and the
    // permission is withdrawn.
    let cancel = simulate(&steady_ticks(), END_US, entry_then(Pass::Cancel));
    assert!(last_change(&cancel) <= STOP_US + LOOP_PHASE_US + PULSE_HALF_PERIOD_US);
    assert!(!cancel.pin.last().unwrap().1);
    pwl(&mut out, "PIN_CANCEL", "pin_cancel", &cancel.pin);
    pwl(&mut out, "MARK_CANCEL", "mark_cancel", &[(STOP_US + LOOP_PHASE_US, true)]);

    // STALL: the timer task is held off for 9 ms every 100 ms (the missed
    // ticks are skipped, as esp_timer is configured to do). The firmware
    // counts this as unbroken pulsing; the circuit must agree.
    let stalled: Vec<u32> = steady_ticks().into_iter().filter(|t| !(50_000..59_000).contains(&(t % 100_000))).collect();
    let stall = simulate(&stalled, END_US, entry_then(Pass::Renew));
    assert!(stall.precharged_at.is_some());
    assert_eq!(stall.precharge_losses, 0, "a 9 ms stall is inside MAX_TICK_GAP_US");
    pwl(&mut out, "PIN_STALL", "pin_stall", &stall.pin);

    // SLOW: the slowest ticking the firmware still calls unbroken, one tick
    // every MAX_TICK_GAP_US. It reports precharged; the deck measures whether
    // the gate really is.
    // That takes PRECHARGE_EDGES x 10 ms = 600 ms, so the logic runs to 700 ms;
    // the deck only needs the first 500 ms, by when the gate has settled.
    let slow_ticks: Vec<u32> = (0..70).map(|i| i * MAX_TICK_GAP_US).collect();
    let slow = simulate(&slow_ticks, 700_000, |now| if now < ENTRY_US { Pass::Cancel } else { Pass::Renew });
    assert!(slow.precharged_at.is_some(), "the firmware does call this precharged");
    let in_deck: Vec<(u32, bool)> = slow.pin.iter().copied().filter(|&(time, _)| time < END_US).collect();
    pwl(&mut out, "PIN_SLOW", "pin_slow", &in_deck);

    // FLASH: while a workout is running the firmware saves progress to flash
    // every 30 s. ESP-IDF suspends every task for the length of a flash
    // operation ("all other tasks are suspended", SPI flash concurrency
    // guide), so both the safety loop and the pulse timer stop, then carry
    // on. 45 ms is a typical 4 KB sector erase; 400 ms is the datasheet worst
    // case the firmware's own comments budget for. The durations are those
    // assumptions, not measurements.
    for (name, stall_us) in [("45", 45_000u32), ("100", 100_000), ("400", 400_000)] {
        let stalled = |t: u32| (FLASH_START_US..FLASH_START_US + stall_us).contains(&t);
        let ticks: Vec<u32> = steady_ticks().into_iter().filter(|&t| !stalled(t)).collect();
        let flash = simulate(&ticks, END_US, |now| {
            if now < ENTRY_US {
                Pass::Cancel
            } else if stalled(now) {
                Pass::Hung
            } else {
                Pass::Renew
            }
        });
        // The pin rests low through the stall and pulsing resumes after it.
        let resumed = flash.pin.iter().find(|&&(time, _)| time >= FLASH_START_US + stall_us).expect("pulses resume");
        assert!(resumed.0 - (FLASH_START_US + stall_us) <= LOOP_PERIOD_US + PULSE_HALF_PERIOD_US, "{}", resumed.0);
        pwl(&mut out, &format!("PIN_FLASH{name}"), &format!("pin_flash{name}"), &flash.pin);
    }
    pwl(&mut out, "MARK_FLASH", "mark_flash", &[(FLASH_START_US, true)]);
    out
}

#[test]
fn committed_trace_matches_the_firmware() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../../sim/traces/liveness_firmware.inc");
    let generated = generate();
    if std::env::var_os("UPDATE_LIVENESS_TRACE").is_some() {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, &generated).unwrap();
        return;
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    assert!(
        committed == generated,
        "{} is stale; regenerate with UPDATE_LIVENESS_TRACE=1",
        path.display()
    );
}
